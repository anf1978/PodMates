// Exercises Claude hook handlers with real subprocesses and isolated files.
// Never edits app data or invokes Claude's interactive permission UI.
import { afterEach, beforeEach, expect, test } from "vitest";
import {
  copyFileSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const project = fileURLToPath(new URL("../", import.meta.url));
let fixture: string;

function write(path: string, text: string): string {
  const file = join(fixture, path);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
  return file;
}

function hook(
  mode: string,
  toolInput: Record<string, unknown> = {},
  extra: Record<string, unknown> = {},
) {
  return spawnSync(process.execPath, [join(fixture, ".claude", "hooks", "workspace.mjs"), mode], {
    cwd: fixture,
    encoding: "utf8",
    input: JSON.stringify({ cwd: fixture, tool_input: toolInput, ...extra }),
    timeout: 20_000,
  });
}

beforeEach(() => {
  fixture = mkdtempSync(join(tmpdir(), "podmates-hooks-"));
  mkdirSync(join(fixture, ".claude", "hooks"), { recursive: true });
  copyFileSync(
    join(project, ".claude", "hooks", "workspace.mjs"),
    join(fixture, ".claude", "hooks", "workspace.mjs"),
  );
});

afterEach(() => {
  rmSync(fixture, { recursive: true, force: true });
});

test.each(["public/data/probe.json", "src/generated/cards.ts", "src/cards.generated.ts"])(
  "blocks a generated path before it exists: %s",
  (file_path) => {
    const result = hook("protect", { file_path });
    expect(result.status).toBe(2);
    expect(result.stderr).toContain("edit its pipeline instead");
  },
);

test("blocks a generated header even when a Write would remove it", () => {
  const file_path = write("src/cards.ts", "// GENERATED by pipelines/cards\nexport {};\n");
  const result = hook("protect", { file_path, content: "export const replacement = 1;\n" });
  expect(result.status).toBe(2);
  expect(readFileSync(file_path, "utf8")).toContain("// GENERATED");
  expect(
    hook("protect", { file_path: "src/new.ts", content: "// GENERATED by a tool\n" }).status,
  ).toBe(2);
});

test("allows ordinary edits, including paths relative to the tool cwd", () => {
  const file_path = write("src/feature.ts", "export const name = 'feature';\n");
  expect(hook("protect", { file_path }).status).toBe(0);
  expect(hook("protect", { file_path: "feature.ts" }, { cwd: join(fixture, "src") }).status).toBe(
    0,
  );
});

test("resolves symlinked parents before permitting a new file", () => {
  mkdirSync(join(fixture, "public", "data"), { recursive: true });
  symlinkSync(join(fixture, "public", "data"), join(fixture, "alias"), "junction");
  expect(hook("protect", { file_path: join("alias", "new.json") }).status).toBe(2);
  expect(hook("protect", { notebook_path: join("alias", "probe.ipynb") }).status).toBe(2);
});

test("reports missing paths and blocks traversal outside the project", () => {
  expect(hook("protect").status).toBe(2);
  const result = hook("protect", { file_path: resolve(fixture, "..", "outside.ts") });
  expect(result.status).toBe(2);
  expect(result.stderr).toContain("outside this project");
});

test("does not format legacy HTML or generated content, without needing installed tools", () => {
  for (const name of ["index.html", "src/cards.generated.ts", "public/data/probe.json"]) {
    const file_path = write(name, " deliberately   unformatted ");
    expect(hook("format", { file_path }).status).toBe(0);
    expect(readFileSync(file_path, "utf8")).toBe(" deliberately   unformatted ");
  }
  const file_path = write("src/header.ts", "// GENERATED by a test\nconst x=1");
  expect(hook("format", { file_path }).status).toBe(0);
  expect(readFileSync(file_path, "utf8")).toBe("// GENERATED by a test\nconst x=1");
});

test("formats and applies ESLint fixes to only the edited file with shell metacharacters", () => {
  symlinkSync(join(project, "node_modules"), join(fixture, "node_modules"), "junction");
  copyFileSync(join(project, "eslint.config.js"), join(fixture, "eslint.config.js"));
  copyFileSync(join(project, ".prettierrc.json"), join(fixture, ".prettierrc.json"));
  write("package.json", '{"type":"module"}');
  const file_path = write("space & quote's.ts", "let value=1\nconsole.log(value)\n");
  const untouched = write("untouched.ts", "let other=2\nconsole.log(other)\n");
  const result = hook("format", { file_path });
  expect(result.stderr).toBe("");
  expect(result.status).toBe(0);
  expect(readFileSync(file_path, "utf8")).toBe("const value = 1;\nconsole.log(value);\n");
  expect(readFileSync(untouched, "utf8")).toBe("let other=2\nconsole.log(other)\n");
}, 25_000);

test("reports edit-check failures rather than silently accepting them", () => {
  symlinkSync(join(project, "node_modules"), join(fixture, "node_modules"), "junction");
  write("eslint.config.js", 'throw new Error("lint configuration failure");\n');
  write("package.json", '{"type":"module"}');
  const result = hook("format", { file_path: write("probe.ts", "export const value=1;\n") });
  expect(result.status).toBe(2);
  expect(result.stderr).toContain("lint configuration failure");
}, 25_000);

test.each([false, true])(
  "Stop runs checks and blocks failures even on retry: %s",
  (stop_hook_active) => {
    write(
      "package.json",
      JSON.stringify({
        scripts: { check: "node -e \"console.log('check-executed');process.exit(1)\"" },
      }),
    );
    const failure = hook("check", {}, { stop_hook_active });
    expect(failure.status).toBe(2);
    expect(failure.stdout).toContain("check-executed");
    expect(failure.stderr).toContain("Workspace hook:");
    write("package.json", JSON.stringify({ scripts: { check: 'node -e "process.exit(0)"' } }));
    expect(hook("check", {}, { stop_hook_active }).status).toBe(0);
  },
  25_000,
);
